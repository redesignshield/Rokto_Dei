export function getDistrictsByDivision(divisionId: string): DistrictItem[] {
  if (!divisionId) return [];
  return DISTRICTS.filter((d) => d.divisionId === divisionId);
}

export function getUpazilasByDistrict(districtId: string): UpazilaItem[] {
  if (!districtId) return [];
  const found = DISTRICTS.find((d) => d.id === districtId);
  return found ? [...found.upazilas] : [];
}

export function isValidLocationHierarchy(
  divisionId: string,
  districtId: string,
  upazilaId: string
): boolean {
  const div = DIVISIONS.find((d) => d.id === divisionId);
  if (!div) return false;
  const dist = DISTRICTS.find(
    (d) => d.id === districtId && d.divisionId === divisionId
  );
  if (!dist) return false;
  return dist.upazilas.some((upz) => upz.id === upazilaId);
}

export function formatLocationLabel(
  divisionId: string,
  districtId: string,
  upazilaId: string,
  lang: AppLanguage = 'bn'
): string {
  const div = DIVISIONS.find((d) => d.id === divisionId);
  const dist = DISTRICTS.find((d) => d.id === districtId);
  const upz = dist?.upazilas.find((item) => item.id === upazilaId);

  const parts = [
    upz ? upz[lang] : upazilaId,
    dist ? dist[lang] : districtId,
    div ? div[lang] : divisionId,
  ].filter(Boolean);

  return parts.join(' · ');
}

export function formatDistrictLabel(
  divisionId: string,
  districtId: string,
  lang: AppLanguage = 'bn'
): string {
  const div = DIVISIONS.find((d) => d.id === divisionId);
  const dist = DISTRICTS.find((d) => d.id === districtId);
  return [dist ? dist[lang] : districtId, div ? div[lang] : divisionId]
    .filter(Boolean)
    .join(' · ');
}

export function getDivisionById(divisionId: string): DivisionItem | undefined {
  return DIVISIONS.find((d) => d.id === divisionId);
}

export function getDistrictById(districtId: string): DistrictItem | undefined {
  return DISTRICTS.find((d) => d.id === districtId);
}
